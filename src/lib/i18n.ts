/**
 * English used to live here as a second, hand-maintained dictionary.
 * It has been removed: English (and any other language) is now produced
 * live by the GTranslate (https://gtranslate.io/) widget wired up in
 * index.html + src/lib/gtranslate.ts, which translates the rendered DOM.
 * UI copy is authored once, in Turkish, as the single source of truth.
 *
 * The `lang` parameter is kept in the signature (and still accepted
 * everywhere it's called) purely so no call site elsewhere in the app
 * needs to change — it's intentionally unused now.
 */
export function t(key: string, _lang: Language = 'tr'): string {
  return tr[key] || key;
}
